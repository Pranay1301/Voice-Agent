def find_location(query: str) -> list:
    """
    Find any location matching the query.
    Returns list of matching locations with their details.
    """
    query_lower = query.lower()
    results = []
    
    # Search stages
    for stage in KNOWLEDGE_BASE["stages"]:
        if query_lower in stage["name"].lower() or query_lower in stage.get("description", "").lower():
            results.append({"type": "Stage", **stage})
    
    # Search masterclass rooms
    for room in KNOWLEDGE_BASE["masterclass_rooms"]:
        if query_lower in room["name"].lower():
            results.append({"type": "Masterclass Room", **room})
    
    # Search lounges
    for lounge in KNOWLEDGE_BASE["lounges"]:
        if query_lower in lounge["name"].lower() or query_lower in lounge.get("description", "").lower():
            results.append({"type": "Lounge", **lounge})
    
    # Search food areas
    for area in KNOWLEDGE_BASE["food_areas"]:
        if query_lower in area["name"].lower():
            results.append({"type": "Food Area", **area})
    
    # Search facilities
    for facility in KNOWLEDGE_BASE["facilities"]:
        if query_lower in facility["name"].lower():
            results.append({"type": "Facility", **facility})
    
    # Search meeting areas
    for area in KNOWLEDGE_BASE["meeting_areas"]:
        if query_lower in area["name"].lower():
            results.append({"type": "Meeting Area", **area})
    
